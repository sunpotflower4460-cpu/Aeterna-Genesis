#!/usr/bin/env python3
"""e060 ノイズ振幅スケジュール — 「係数を臨界を越えて動かす」核生成の代替。

## なぜこれに切り替えるか

`quench.py` の当初の二段クエンチは、線形係数（SHの r、MCの k0）を一様状態が
**不安定な側**（SHなら r>0）へ一時的に動かし、模様を核生成させてから元の域へ
落とす方式だった。しかしPhase 1本番の結果、これは主に「全域を埋める」
（FILLS_DOMAIN 55.2%）に落ちるだけで、単一個体には近づかなかった。加えて
r>0 側では数値ステッパーの無条件安定性の保証が失われ、数値破綻が急増した
（23.2%、ただし主因はbであってrではないと判明——後述）。

より根本的な問題は、r>0 への遷移そのものが「一様状態を積極的に不安定化させて
構造を強制発生させる」操作であり、モナド前提M3（内的原理からの展開）に対して
やや強引だったこと。**双安定域（r<0）に留まったまま、ノイズという「温度」を
一時的に上げる**方式の方が、系が元々持つ双安定性（bump入りICで実証済みの
局在解の存在）だけを使って自発的な核生成を待つ、より穏当な操作になる。

## これは第8監査に触れないか

触れない。位置・形・個数・方向のいずれも与えていない——**振幅という数だけ**を
時間の関数として与える。これは既存の `g001_ginzburg_landau_quench` が
`quench_duration` で eps(t) を掃引するのと同じ格の「プロトコル」である
（`docs/GENESIS_AUTOPILOT.md` が正当な始原条件操作として扱う範疇）。ノイズは
むしろ「一様乱雑さ」そのものであり、対称性を破る情報を一切持たない。

## 実装方針

段1（核生成、`switch_frac` の割合のステップ数）: 毎ステップ、ゼロ平均ノイズを
振幅 `amp1` で場に加算する（一種の熱浴）。
段2（保持）: 振幅を `amp2`（既定の探索軸 `noise_amplitude` の値、通常は小さい）
に落とす。段2の法則パラメータ（r や k0）は **段1・段2を通じて一切変更しない**
——変えるのはノイズ振幅だけ。
"""
from __future__ import annotations

import numpy as np

from . import whites


def stage_lengths(total_steps, switch_frac):
    frac = min(max(float(switch_frac), 0.05), 0.95)
    n1 = int(round(total_steps * frac))
    return n1, int(total_steps) - n1


def kick(shape, amp, rng, dt=1.0):
    """毎ステップの熱浴ノイズ「項」（ゼロ平均・空間一様乱雑、形を与えない）を返す。

    呼び出し側が場に加算する。dt でスケールするのは、時間刻みに依存しない
    ノイズ強度（拡散のランダムウォークと同じ dt^0.5 スケーリング）にするため。
    これも数値的正しさの話であって、答えを置く操作ではない。
    """
    return float(amp) * np.sqrt(max(dt, 1e-12)) * whites.zero_mean_noise(shape, rng)
