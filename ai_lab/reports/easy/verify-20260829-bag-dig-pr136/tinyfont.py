def text_mask(s: str) -> np.ndarray:
    """Return a (5, 4*len(s)-1) bool mask of the string at 3x5 per glyph, 1 px gap."""
    s = s.upper()
    cols = []
    for ch in s:
        g = GLYPHS.get(ch, GLYPHS["?"])
        cols.append(np.array([[c == "1" for c in row] for row in g], bool))
        cols.append(np.zeros((5, 1), bool))
    if not cols:
        return np.zeros((5, 0), bool)
    return np.concatenate(cols[:-1], axis=1)


def draw_text(canvas: np.ndarray, s: str, y: int, x: int, scale: int = 2,
              color=(20, 20, 20)) -> None:
    """Stamp `s` onto an (H, W, 3) uint8 canvas at top-left (y, x). In place."""
    m = text_mask(s)
    if m.size == 0:
        return
    m = np.kron(m, np.ones((scale, scale), bool))
    h, w = m.shape
    H, W, _ = canvas.shape
    h = min(h, max(0, H - y))
    w = min(w, max(0, W - x))
    if h <= 0 or w <= 0:
        return
    sub = canvas[y:y + h, x:x + w]
    sub[m[:h, :w]] = np.asarray(color, np.uint8)


def text_width(s: str, scale: int = 2) -> int:
    return max(0, (4 * len(s) - 1)) * scale
